#!/usr/bin/env bash
# Generates the real service keys for aurix-testnet-2: gateway signer, faucet, N attestors, M guardians.
#
# Usage: keygen.sh [OUT_DIR]            (default ./aurix-keys; must not exist yet)
# Env:   AURIXD (aurixd), ATTESTORS (2), GUARDIANS (2), KEYRING_BACKEND (test|file, default test),
#        GUARDIAN_QUORUM (default: GUARDIANS)
#
# Each key is a fresh 24-word BIP39 mnemonic from `aurixd keys add --output json` (coin type 118,
# m/44'/118'/0'/0/0: the services derive the same address). Everything lands in OUT_DIR (mode 0700):
#   keyring/                   the aurixd keyring (test = unencrypted inside the 0700 dir; file = passphrase)
#   <role>.env                 mode 0600, the env file for that service (<PREFIX>_MNEMONIC=...) — SECRET
#   addresses.txt              role,address(,pubkey) — public
#   anchor_signers.txt         gateway + attestor addresses, input of coordinator-pregenesis.sh — public
# Only addresses are printed. Move each .env to its host (e.g. `docker compose --env-file`), keep an
# offline encrypted backup of the mnemonics, then delete OUT_DIR from the machine that generated it.
set -euo pipefail
source "$(dirname "$0")/common.sh"
need jq; need base64; need od
OUT=${1:-./aurix-keys}; ATTESTORS=${ATTESTORS:-2}; GUARDIANS=${GUARDIANS:-2}
KEYRING_BACKEND=${KEYRING_BACKEND:-test}; GUARDIAN_QUORUM=${GUARDIAN_QUORUM:-$GUARDIANS}
[[ $KEYRING_BACKEND == test || $KEYRING_BACKEND == file ]] || die "KEYRING_BACKEND must be test or file"
[[ -e "$OUT" ]] && die "$OUT already exists: refusing to overwrite keys"
umask 077
mkdir -p "$OUT/keyring"; chmod 700 "$OUT" "$OUT/keyring"

new_key() { # name -> sets ADDR, MNEMONIC, PUBHEX
  local j
  j=$($BIN keys add "$1" --keyring-backend "$KEYRING_BACKEND" --keyring-dir "$OUT/keyring" --output json 2>/dev/null) \
    || die "aurixd keys add $1 failed"
  ADDR=$(jq -r .address <<<"$j"); MNEMONIC=$(jq -r .mnemonic <<<"$j")
  [[ $ADDR == aur1* && $(wc -w <<<"$MNEMONIC") -ge 12 ]] || die "unexpected keys add output for $1"
  PUBHEX=$(jq -r .pubkey <<<"$j" | jq -r .key | base64 -d | od -An -tx1 | tr -d ' \n')
}
write_env() { # file lines...
  local f=$1; shift
  printf '%s\n' "# generated by keygen.sh $(date -u +%Y-%m-%dT%H:%M:%SZ) — SECRET, mode 0600, never commit" "$@" > "$f"
  chmod 600 "$f"
}

echo "role,address,pubkey" > "$OUT/addresses.txt"
new_key gateway; GW_ADDR=$ADDR; GW_MN=$MNEMONIC; echo "gateway,$ADDR" >> "$OUT/addresses.txt"
new_key faucet;  FAUCET_ADDR=$ADDR; FAUCET_MN=$MNEMONIC; echo "faucet,$ADDR" >> "$OUT/addresses.txt"
echo "$GW_ADDR" > "$OUT/anchor_signers.txt"
for ((i = 1; i <= ATTESTORS; i++)); do
  new_key "attestor-$i"; echo "attestor-$i,$ADDR" >> "$OUT/addresses.txt"; echo "$ADDR" >> "$OUT/anchor_signers.txt"
  write_env "$OUT/attestor-$i.env" "AURIX_ENV=production" "ATTESTOR_MNEMONIC=\"$MNEMONIC\"" \
    "CHAIN_ID=$CHAIN_ID" "CHAIN_REST=https://CHANGE_ME_NODE:1317" \
    "PAYPAL_BASE_URL=https://api-m.sandbox.paypal.com" "PAYPAL_CLIENT_ID=CHANGE_ME" "PAYPAL_CLIENT_SECRET=CHANGE_ME"
done
PUBKEYS=""
for ((i = 1; i <= GUARDIANS; i++)); do
  new_key "guardian-$i"; echo "guardian-$i,$ADDR,$PUBHEX" >> "$OUT/addresses.txt"; PUBKEYS+="${PUBKEYS:+,}$PUBHEX"
  write_env "$OUT/guardian-$i.env" "AURIX_ENV=production" "GUARDIAN_MNEMONIC=\"$MNEMONIC\"" "GUARDIAN_CHAIN_ID=$CHAIN_ID"
done
write_env "$OUT/gateway.env" "AURIX_ENV=production" "GATEWAY_MNEMONIC=\"$GW_MN\"" "FAUCET_MNEMONIC=\"$FAUCET_MN\"" \
  "GUARDIAN_URLS=https://CHANGE_ME_GUARDIAN_1,https://CHANGE_ME_GUARDIAN_2" "GUARDIAN_QUORUM=$GUARDIAN_QUORUM" \
  "GUARDIAN_PUBKEYS=$PUBKEYS" "CHAIN_RPC_URL=http://CHANGE_ME_NODE:26657" "CHAIN_REST_URL=http://CHANGE_ME_NODE:1317" \
  "PAYPAL_ENV=sandbox" "PAYPAL_CLIENT_ID=CHANGE_ME" "PAYPAL_CLIENT_SECRET=CHANGE_ME" "PAYPAL_WEBHOOK_ID=CHANGE_ME"
chmod 644 "$OUT/addresses.txt" "$OUT/anchor_signers.txt"

echo "keys written to $OUT (0700); secrets only in $OUT/*.env (0600) and $OUT/keyring"
cut -d, -f1,2 "$OUT/addresses.txt" | tail -n +2 | tr , " "
echo
echo "next: FAUCET_ADDR=$FAUCET_ADDR scripts/coordinator-pregenesis.sh operators.csv $OUT/anchor_signers.txt"
